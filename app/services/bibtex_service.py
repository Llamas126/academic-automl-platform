def references_bibtex(citation_keys: set[str], library_versions: dict[str, str] | None = None) -> str:
    versions = library_versions or {}
    header = (
        "% Bibliography generated by academic-automl-platform\n"
        "% Software versions recorded at run time are included as notes.\n\n"
    )
    chunks = [header]
    for key in sorted(citation_keys):
        entry = BIB_ENTRIES.get(key)
        if entry is None:
            continue
        version = _version_for_key(key, versions)
        if version:
            entry = entry.rstrip("}\n") + f",\n  note    = {{Version {version}}}\n}}\n"
        else:
            entry += "\n"
        chunks.append(entry + "\n")
    return "".join(chunks)


